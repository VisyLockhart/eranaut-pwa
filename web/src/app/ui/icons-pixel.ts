/** 把點陣圖(每列一個字串,'#' 為實心)轉成 SVG 路徑:同一列連續的點合併成一個矩形,縮放時邊緣保持銳利 */
function bitmap(rows: readonly string[], extra = ''): string {
  const w = Math.max(...rows.map((r) => r.length));
  let d = '';
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  return raw(w, rows.length, d, extra);
}

function raw(w: number, h: number, d: string, extra = ''): string {
  return `<svg width="100%" height="100%" viewBox="0 0 ${w} ${h}" fill="currentColor" fill-rule="evenodd" shape-rendering="crispEdges" ${extra}><path d="${d}"/></svg>`;
}

